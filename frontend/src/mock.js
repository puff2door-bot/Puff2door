const parsePuffs = (name) => {
  let m = name.match(/\b(\d{1,3})K\b/);
  if (m) return parseInt(m[1], 10) * 1000;
  m = name.match(/\b(\d{4,5})\s*PUFF/);
  if (m) return parseInt(m[1], 10);
  m = name.match(/\bTN(\d{4})\b/);
  if (m) return parseInt(m[1], 10);
  return null;
};

